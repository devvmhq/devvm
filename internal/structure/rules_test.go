// callerCases break and keep callers.
func callerCases() []ruleCase {
	r := rules{callers: map[string]string{"internal/state.ReadHash": "internal/vm/finder.go"}}
	const finder = "package vm\n\nimport \"example.com/m/internal/state\"\n\nfunc f() { state.ReadHash() }\n"
	return []ruleCase{
		{
			name: "its function called outside its file",
			files: map[string]string{
				"internal/vm/finder.go": finder,
				"internal/vm/a.go":      "package vm\n\nimport st \"example.com/m/internal/state\"\n\nfunc g() { st.ReadHash() }\n",
			},
			r:    r,
			want: &want{ruleOwners, "calls state.ReadHash: only internal/vm/finder.go does"},
		},
		{
			name:  "its file no longer calling it",
			files: map[string]string{"internal/vm/finder.go": "package vm\n"},
			r:     r,
			want:  &want{ruleOwners, "internal/vm/finder.go doesn't call internal/state.ReadHash: take it out"},
		},
		{
			name: "its file, its own package and a test calling it",
			files: map[string]string{
				"internal/vm/finder.go":  finder,
				"internal/state/a.go":    "package state\n\nfunc ReadHash() {}\n\nfunc g() { ReadHash() }\n",
				"internal/vm/vm_test.go": "package vm\n\nimport \"example.com/m/internal/state\"\n\nfunc h() { state.ReadHash() }\n",
				"internal/cli/a.go":      "package cli\n\nimport \"example.com/m/internal/state\"\n\nfunc h() { state.ReadVM() }\n",
			},
			r: r,
		},
		{
			name: "its method called outside its file",
			files: map[string]string{
				"internal/vm/agents.go": "package vm\n\nfunc f(d interface{ AgentSettings(string) string }) { d.AgentSettings(\"x\") }\n",
				"internal/vm/sync.go":   "package vm\n\nfunc g(e struct{ Dirs interface{ AgentSettings(string) string } }) { e.Dirs.AgentSettings(\"x\") }\n",
			},
			r:    rules{callers: map[string]string{"internal/paths.Dirs.AgentSettings": "internal/vm/agents.go"}},
			want: &want{ruleOwners, "calls paths.AgentSettings: only internal/vm/agents.go does"},
		},
		{
			name: "its method called in its file and its own package",
			files: map[string]string{
				"internal/vm/agents.go": "package vm\n\nfunc f(d interface{ AgentSettings(string) string }) { d.AgentSettings(\"x\") }\n",
				"internal/paths/a.go":   "package paths\n\ntype Dirs struct{}\n\nfunc (Dirs) AgentSettings(string) string { return \"\" }\n\nfunc g() { Dirs{}.AgentSettings(\"x\") }\n",
			},
			r: rules{callers: map[string]string{"internal/paths.Dirs.AgentSettings": "internal/vm/agents.go"}},
		},
	}
}

// Each rule fails on code that breaks it, naming the rule, and passes
// what it allows.
func TestRulesFail(t *testing.T) {
	var broken []string // the layer violations' texts
	for _, tc := range slices.Concat(methodCases(), varCases(), layerCases(), ownerCases(), agentCases(), separatorCases(), runnerCases(), pathCases(), callerCases()) {
		t.Run(tc.name, func(t *testing.T) {
			fsys := fstest.MapFS{"go.mod": {Data: []byte("module example.com/m\n\ngo 1.27\n")}}
			for name, src := range tc.files {
				fsys[name] = &fstest.MapFile{Data: []byte(src)}
			}
			m, err := load(fsys)
			if err != nil {
				t.Fatal(err)
			}
			r := tc.r
			if r.maxMethods == 0 {
				r.maxMethods = 2
			}
			if r.layers == nil {
				r.layers = devvm().layers
			}
			if r.commands == nil {
				r.commands = devvm().commands
			}
			if r.envOwner == "" {
				r.envOwner = devvm().envOwner
			}
			if r.envOwners == nil {
				r.envOwners = devvm().envOwners
			}
			if r.literals == nil {
				r.literals = devvm().literals
			}
			if r.names == nil {
				r.names, r.namesFree = devvm().names, devvm().namesFree
			}
			if r.separators == nil {
				r.separators = devvm().separators
			}
			if r.pathsOwner == "" {
				r.pathsOwner = devvm().pathsOwner
			}
			vs := check(m, r)
			if tc.want == nil {
				if len(vs) != 0 {
					t.Errorf("got %q, want none", vs)
				}
				return
			}
			if len(vs) != 1 || vs[0].rule != tc.want.rule || !strings.Contains(vs[0].text, tc.want.text) {
				t.Errorf("got %q, want one %s violation saying %q", vs, tc.want.rule, tc.want.text)
			}
			if len(vs) == 1 && vs[0].rule == ruleLayers {
				broken = append(broken, vs[0].text)
			}
		})
	}
	// Every layer has a case that breaks it.
	for _, l := range devvm().layers {
		if !slices.ContainsFunc(broken, func(text string) bool { return strings.HasSuffix(text, ": "+l.name) }) {
			t.Errorf("no case breaks layer %q", l.name)
		}
	}
}
